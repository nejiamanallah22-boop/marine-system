/**
 * التحقق من أن المستخدم لديه صلاحية معينة
 * @param {string} permission - اسم الصلاحية
 * @param {string} role - دور المستخدم
 * @returns {boolean}
 */
function hasPermission(permission, role) {
    if (!permission || !role) return false;
    const allowedRoles = PERMISSIONS[permission];
    if (!allowedRoles) return false;
    return allowedRoles.includes(role);
}

/**
 * الحصول على قائمة الصلاحيات لدور معين
 * @param {string} role - دور المستخدم
 * @returns {string[]}
 */
function getPermissionsByRole(role) {
    const userPermissions = [];
    for (const [permission, roles] of Object.entries(PERMISSIONS)) {
        if (roles.includes(role)) {
            userPermissions.push(permission);
        }
    }
    return userPermissions;
}

/**
 * التحقق من أن المستخدم مسؤول
 * @param {string} role - دور المستخدم
 * @returns {boolean}
 */
function isAdmin(role) {
    return role === 'مسؤول';
}

/**
 * التحقق من أن المستخدم محرر إقليمي
 * @param {string} role - دور المستخدم
 * @returns {boolean}
 */
